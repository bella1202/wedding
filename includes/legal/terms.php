2) 이용자는 본인이 설정한 비밀번호로 게시물을 삭제할 수 있습니다.<br>
3) 회사는 관련 법령 위반 또는 제5조 위반이 확인되거나 신고가 접수된 게시물에 대해 사전 통지 없이 삭제·비공개 처리할 수 있습니다.</p>

<p><strong>제7조(개인정보 보호)</strong><br>
