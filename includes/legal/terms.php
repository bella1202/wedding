<p><strong>제4조(서비스의 제공)</strong><br>
1) 회사는 연중무휴 서비스를 제공하기 위해 노력합니다. 다만 시스템 점검, 장애, 천재지변 등 불가피한 사유가 있는 경우 서비스가 일시 중단될 수 있습니다.<br>
2) 회사는 서비스의 일부 기능을 추가·변경·종료할 수 있으며, 중요한 변경이 있는 경우 합리적인 방법으로 안내합니다.</p>

